// Bundles the CLAP webview GUI and embeds it as C++ data (src/clap/WebviewResources.h).
// Usage: node build-wclap-gui.mjs <output.cpp>
import {build} from 'esbuild';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..');
const output=resolve(process.argv[2]||root+'/build/wclap/WebviewResources.cpp');
const bundle=await build({entryPoints:[root+'/web/wclap/gui.ts'],bundle:true,format:'esm',target:'es2022',
 minify:true,legalComments:'eof',write:false});
const files=[
 ['/index.html','text/html; charset=utf-8',await readFile(root+'/web/wclap/index.html')],
 ['/gui.js','text/javascript; charset=utf-8',Buffer.from(bundle.outputFiles[0].contents)],
];
const quote=text=>JSON.stringify(text);
let source='// Generated by web/scripts/build-wclap-gui.mjs. Do not edit.\n#include "WebviewResources.h"\nnamespace helm {\nnamespace {\n';
files.forEach(([,,data],index)=>{
 source+=`const unsigned char file${index}[]={`;
 for(let i=0;i<data.length;++i)source+=(i%32?'':'\n')+data[i]+',';
 source+='0};\n';
});
source+='}\nconst EmbeddedResource webviewResources[]={\n';
files.forEach(([path,mime,data],index)=>{source+=` {${quote(path)},${quote(mime)},file${index},${data.length}u},\n`;});
source+=`};\nconst uint32_t webviewResourceCount=${files.length};\n}\n`;
await mkdir(dirname(output),{recursive:true});
let previous='';try{previous=await readFile(output,'utf8');}catch{}
if(previous!==source)await writeFile(output,source);
